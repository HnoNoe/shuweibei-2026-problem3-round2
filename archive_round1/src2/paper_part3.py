h3(doc, "5.2.2 预留决策：最小预留的弱占优性")
para(doc,
     "命题 1（最小预留弱占优）：设当前时刻 t、区域到服务区域距离 D，则对任意可行预留 b≥0.2，"
     "取 b₀=0.2 的执行满足：(i) 完成时刻不变；(ii) 设备占用时间不变或更短；(iii) 费用严格更小；"
     "(iv) 预留空闲为零。因此，以加权完成率/准时率为目标的策略取 b=0.2 弱占优于一切更大的预留。")
para(doc,
     "证明：服务开始 s=t+D+0.5 与 b 无关，完成时刻 C=s+p 与 b 无关，(i) 成立。设备下次可用"
     "时刻为 s+max(p,b)；由于对任意合法抽样区间 d≥1.2 s 且 α∈{0.75,1,1.5}、β≥0，有 "
     "p=αd+β≥0.75×1.2=0.9>0.2=b₀，故 max(p,b₀)=p，而 max(p,b)≥p，(ii) 成立。费用"
     " 2+0.1b+0.2D 关于 b 严格递增，(iii) 成立。预留空闲 max(b−p,0)，因 b₀<p 恒为零，(iv) 成立。"
     "证毕。")
formula(doc, "C = s + p", "5-2")
formula(doc, "t_next = s + max(p, b)", "5-3")
para(doc,
     "推论：observed_overrun=Σmax(min(p,H−s)−b,0) 在 b=0.2 时达到其（不可避免的）最大值。"
     "超时占用是容量风险的度量而非失败：它以设备占用为代价换取完成时刻与费用的最优。若主目标改为"
     "成本/容量风险，可用更大的 b 把 overrun 换成 idle，见 5.3 节权衡分析。")

h3(doc, "5.2.3 审查决策：信息价值分析")
para(doc,
     "付费审查的期望收益等于“更长前缀带来的决策改进”的期望提升。5.1.2 节已证明前缀对时长无"
     "预测力，因此审查不能改进排序、预留或防护决策中的任何一个；其成本为 1 单位/次并占用设备 "
     "1 s（同样受 K 与 B 约束）。期望信息价值约为零而成本为正，故最优策略不买审查。我们在调参中"
     "以“选择性审查”规则（对高分位差且高权重的作业买审查）做了实证检验：加入审查后各案例准时率"
     "均无提升且成本上升，与理论分析一致，最终策略的 observations 恒为 0。")

h3(doc, "5.2.4 排序模型：ATC-travel 指数、截断防护与预算取舍")
para(doc,
     "排序是剩余的唯一核心决策。经典 ATC（apparent tardiness cost）指数在 WSPT 的效率项上叠加"
     "交期紧迫度指数衰减[2]，在带权误工单机问题上显著优于纯 WSPT。考虑到本题中移动与换型时间"
     "占服务前导的显著比例（最远区域 D=2，前导 D+0.5 与族内中位时长同阶），我们将有效加工时长"
     "定义为 peff_j=E[p_j]+D_j+0.5，设计 ATC-travel 指数：")
formula(doc, "I_{j} = (w_{j}/peff_{j})·exp(−max(S_{j},0)/(κ·peff_{j}))", "5-4")
para(doc,
     "其中期望松弛 S_j = due_j − (s_j + E[p_j])，有效加工时长 peff_j = E[p_j] + D_j + 0.5。"
     "每个设备空闲时刻，在全部“已释放、前序完成、预算可付、s+b≤H”的作业中取 I_j 最大者执行。"
     "在此之上叠加两项风险机制。其一为截断防护：仅当作业以 q 分位时长估计仍能在 H 前完成时才"
     "允许执行，即")
formula(doc, "s_j + Q_q(p_j) ≤ H", "5-5")
para(doc,
     "其中 q 为调参确定的分位水平（冻结值 0.90）；若防护过滤后无候选，才退而执行无防护候选或等待，"
     "避免长时长作业在 horizon 末端白烧预算。其二为预算取舍：当剩余预算不足以按最低费用覆盖全部"
     "剩余作业时，按价值密度 w_j·(1+0.5×后继数)/最低费用 升序舍去尾部作业，保证预算花在权重"
     "效率最高的作业上（该机制在 S3 的紧预算情形下作为保险存在）。无可行作业且存在未来释放时等待"
     "至最近释放时刻，否则停止。")

