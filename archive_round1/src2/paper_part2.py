# ================= 二、问题分析 =================
h1(doc, "二、问题分析")

h2(doc, "2.1 问题一的分析")
para(doc,
     "时长估计是全部决策的基础，但本题的数据特点决定了它不是一个常规的点预测问题。首先，343 个"
     "合格区间的时长跨度极大（1.2~125 s），均值 6.34 s 而中位数仅约 4 s，呈明显重右尾；其次，"
     "作业时长取决于整个标注区间的动作内容，而策略最多只能合法获得前 1.0 s 的前缀数据；再次，"
     "三个数据集（EgoDemo/EgoPro/EgoStandard）采集设备与格式均不同，作业族 P/A/L 只是抽样"
     "分层标签而非动作类别标签。因此，若直接套用回归模型做时长预测，很可能高估前缀信息的价值。"
     "我们决定在建立任何预测模型之前，先以按环境分组的交叉验证严格回答“前缀能预测多少”，"
     "其结果将直接决定信息审查（花钱买更长前缀）是否值得——这正是连接问题一与问题二的枢纽。")
para(doc,
     "在分布建模上，重尾特征提示应对时长做对数变换；族间均值差异的显著性需要用方差分析检验，"
     "以确定分层的必要性。综合以上分析，问题一的建模路线为：分布诊断 → 前缀可预测性检验 → "
     "family 分层对数正态不确定性模型。")

h2(doc, "2.2 问题二的分析")
para(doc,
     "问题二属于带释放时刻、交期、权重、前序约束、序列相关移动时间、成本预算与信息购买的单设备"
     "随机调度问题，该类问题在确定性情形下已是 NP-hard[1]，随机情形下通常采用基于优先指数的"
     "启发式规则[2]或基于仿真的策略搜索[3][4]。")
para(doc,
     "仔细审视题目协议可以发现两个可解析利用的结构。其一，完成时刻 C=s+p 与预留 b 无关，"
     "设备下次可用时刻为 s+max(p,b)，而费用 2+0.1b+0.2D 与预留空闲 max(b−p,0) 均随 b 递增；"
     "由于合格区间长度不小于 1.2 s 且 α≥0.75，故 p≥0.9 s>0.2 s 恒成立，b 取最小值 0.2 时"
     "设备占用与完成时刻不变、费用与空闲同时最小——最小预留弱占优于任意更大的预留。其二，"
     "付费审查的唯一收益是更长的前缀，而其价值完全取决于前缀对时长的预测力；若问题一证明前缀"
     "无预测力，则审查的期望信息价值约为零，最优策略不应购买任何审查。这两个结论将决策空间从"
     "“排序+预留+审查”三维压缩到以排序为核心的单维问题。")
para(doc,
     "排序本身仍需处理三重不确定性带来的风险：时长不确定使期望松弛难以精确；启动过晚的作业可能"
     "跨越 H 被截断（成本照付但作业不计完成）；预算约束在 S3 案例中接近紧约束（16 个作业最低"
     "费用合计约 37~39，预算仅 40）。因此我们在 ATC 指数的基础上加入截断防护与预算内价值密度"
     "取舍，并以样本平均近似（SAA）rollout 作对照实验检验改进空间。")

h2(doc, "2.3 问题三的分析")
para(doc,
     "问题三要求报告目标的权衡与对时长映射的敏感性。预留 b 是天然的权衡旋钮：b 不影响完成时刻，"
     "但大预留把“超时占用（overrun）”换成“预留空闲（idle）”并增加费用，故扫描 b 的分位取法"
     "即可得到准时率—成本—风险的三维权衡面。对 5 组映射的验证同时检验策略在题目假设扰动下的"
     "稳健性；最后在测试记录上以冻结策略做模拟终测，检验其对未见环境的泛化能力。")

# ================= 三、模型假设 =================
h1(doc, "三、模型假设")
para(doc, "1. 题目所给数据与协议参数（任务表、区域坐标、源区间索引、公共条件）真实可靠，"
          "仿真器严格按协议实现，策略只使用决策时刻合法可见的信息；", indent_chars=0)
para(doc, "2. 同一作业族内所有合格源区间的时长可视为来自同一分布的样本，族间分布允许不同"
          "（该假设的有效性由 5.1 节的方差分析检验支持）；", indent_chars=0)
para(doc, "3. 族内时长经对数变换后可用正态分布近似，尾部风险以解析分位数刻画；", indent_chars=0)
para(doc, "4. 每次 trial 内作业之间相互独立，仅通过设备占用、预算与前序约束耦合；", indent_chars=0)
para(doc, "5. 付费审查仅释放更长的演示前缀，不产生协议之外的信息价值；", indent_chars=0)
para(doc, "6. 策略在验证集上调定并冻结全部超参数，此后不再使用任何验证/测试信息修改策略。", indent_chars=0)

