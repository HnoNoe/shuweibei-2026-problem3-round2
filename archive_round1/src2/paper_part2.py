h2(doc, "1.1 问题背景")
para(doc,
     "仓储补货是人工作业高度密集的场景，利用第一人称视角的演示数据（双手 21 个关键点的位置与"
     "姿态、头部及双目相机位姿、时间戳与手部质量标志）对人类补货动作进行记录驱动回放，是训练与"
     "评估作业策略的重要途径。题目给出 36 个补货作业，分为 S1、S2、S3 三个相互独立的案例，每个"
     "案例在零时刻从初始区域 Z0 出发，设备为一台不可抢占的单一作业单元，服务区域共 5 个"
     "（Z0~Z4，二维坐标已知），区域间以速度 1 移动且每次执行附加 0.5 s 换型时间。")
para(doc,
     "每个作业具有释放时刻 release_s（最早可获得信息时刻）、期望完成时刻 due_s、优先级权重"
     " priority_weight、服务区域 zone_id 以及前序作业约束；作业的真实服务时长 p = αd + β，"
     "其中 d 为从源记录中按作业族（P/A/L）均匀有放回抽样的标注区间时长，α、β 为时长映射"
     "参数（名义取 α=1.0，β=0.5 s，另有四组敏感性映射）。策略在决策时不知道 d 的真值：每个作业"
     "仅免费释放其源记录前 0.2 s 的数值数据，支付 1 个成本单位并占用设备 1 s 可将可见前缀延长"
     "至 0.6 s、1.0 s（每作业至多两次，且受案例级观察上限 K 与预算 B 约束）。执行动作需选择"
     "预留服务时长 b≥0.2 s，费用为 2+0.1b+0.2D（D 为当前区域到服务区域的欧氏距离），并要求"
     "累计成本不超过 B、计划动作不跨越 horizon H。三个案例的公共参数如表 1-1 所示。")
